// Embeds drizzle-kit SQL migrations into src/migrations.ts so the Durable Object / node:sqlite can apply them.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const dir = join(root, "migrations");
const files = readdirSync(dir).filter((f) => f.endsWith(".sql")).sort();
const list = files.map((f) => ({
  name: f.replace(/\.sql$/, ""),
  statements: readFileSync(join(dir, f), "utf8").split("--> statement-breakpoint").map((s) => s.trim()).filter(Boolean),
}));
writeFileSync(
  join(root, "src/migrations.ts"),
  `// AUTO-GENERATED by scripts/embed-migrations.mjs — do not edit.\nexport const MIGRATIONS: { name: string; statements: string[] }[] = ${JSON.stringify(list, null, 2)};\n`,
);
console.log(`embedded ${files.length} migration(s)`);
